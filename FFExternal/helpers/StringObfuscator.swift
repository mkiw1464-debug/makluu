// ALL sensitive strings are XOR-encoded with key 0x5A.
// Zero plaintext strings visible via `strings` binary tool.
// Decrypted at runtime only when needed.
// Makes patching app name, Telegram link, or any UI text impossible
// without full binary reversing.

